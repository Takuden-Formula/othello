/*
 * Measures the Multi-ProbCut table src/mpc_sigma.h:
 *   mpc_calib <positions> data.bin... > ../../src/mpc_sigma.h
 * For sample positions from self-play data, searches every depth 1..CALIB_DEPTH with a full window
 * (MPC off) and records how far the deep value is from the shallow one used by the cut
 * (depth d vs d - 2*ceil(d/4)). sigma = root mean square of that difference, per phase (empties / 6)
 * and depth; deeper depths are extrapolated from the last measured ones.
 */
#include "../../src/engine.c"
#include <stdio.h>
#include <math.h>

#ifdef _WIN32
#include <windows.h>
uint32_t oth_millis(void) { return (uint32_t)GetTickCount(); }
#else
#include <time.h>
uint32_t oth_millis(void)
{
    struct timespec ts;
    clock_gettime(CLOCK_MONOTONIC, &ts);
    return (uint32_t)(ts.tv_sec * 1000u + ts.tv_nsec / 1000000u);
}
#endif

#define CALIB_DEPTH 10

int main(int argc, char **argv)
{
    static double sq[11][MPC_MAX_DEPTH + 1];
    static long cnt[11][MPC_MAX_DEPTH + 1];
    long want, got = 0, seen = 0;
    int a, g, d;
    if (argc < 3) { fprintf(stderr, "usage: mpc_calib positions data.bin...\n"); return 1; }
    want = atol(argv[1]);
    oth_init();
    mpc_on = 0;
    for (a = 2; a < argc && got < want; a++) {
        FILE *f = fopen(argv[a], "rb");
        unsigned char b[17];
        if (!f) continue;
        while (got < want && fread(b, 17, 1, f) == 1) {
            uint64_t P, O;
            int ne, v[CALIB_DEPTH + 1];
            if (seen++ % 97) continue;              /* spread the sample over many games */
            memcpy(&P, b, 8); memcpy(&O, b + 8, 8);
            ne = 64 - pc(P | O);
            if (ne < 14 || ne > 58 || !oth_moves(P, O)) continue;
            oth_new_game();
            t_start = oth_millis(); t_limit = 0x7FFFFFFF; aborted = 0;
            for (d = 0; d <= CALIB_DEPTH && d < ne; d++) { tt_gen++; v[d] = search(P, O, d, -INF, INF, 0); }
            for (d = MPC_MIN_DEPTH; d <= CALIB_DEPTH && d < ne; d++) {
                double x = v[d] - v[mpc_shallow(d)];
                /* a proven win/loss is not an evaluation error */
                if (abs(v[d]) > OTH_EVAL_MAX || abs(v[mpc_shallow(d)]) > OTH_EVAL_MAX) continue;
                sq[ne / 6][d] += x * x;
                cnt[ne / 6][d]++;
            }
            got++;
            if (got % 100 == 0) fprintf(stderr, "%ld\n", got);
        }
        fclose(f);
    }
    printf("/* Multi-ProbCut sigma [empties / 6][depth] in eval units (100 = 1 disc).\n"
           " * Generated by tools/train/mpc_calib.c from %ld positions; depths above %d extrapolated. */\n",
           got, CALIB_DEPTH);
    for (g = 0; g < 11; g++) {
        double s[MPC_MAX_DEPTH + 1] = { 0 };
        printf("    {");
        for (d = 0; d <= MPC_MAX_DEPTH; d++) {
            if (d >= MPC_MIN_DEPTH && d <= CALIB_DEPTH && cnt[g][d] >= 20) s[d] = sqrt(sq[g][d] / cnt[g][d]);
            else if (d > CALIB_DEPTH && s[d - 2] > 0 && s[d - 4] > 0)     /* same parity, same growth */
                s[d] = s[d - 2] + (s[d - 2] > s[d - 4] ? s[d - 2] - s[d - 4] : 0);
            printf("%s%4d", d ? "," : " ", (int)lround(s[d]));
        }
        printf(" },\n");
    }
    return 0;
}
